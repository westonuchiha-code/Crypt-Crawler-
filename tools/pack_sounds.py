"""Build sounds.js (window.SOUNDS = {file: mp3 data uri}, window.SOUND_KEYS = {game key: file}) from art/sounds/.

Usage: python3 tools/pack_sounds.py [<freedoom dir> <blasphemer dir>]
With the two checkouts given, first copies the .wav files named in tools/sound_cast.py into art/sounds/<set>/
(same repositories and commits as tools/import_enemies.py). Needs ffmpeg. Each file is stored once, however many
keys use it, as a small mono MP3.
"""
import sys, os, json, base64, shutil, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sound_cast import all_keys, SETS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
keys = all_keys()
if len(sys.argv) == 3:
    src = {'f': sys.argv[1], 'b': sys.argv[2]}
    for s, name in SETS.items():
        out = os.path.join(ROOT, 'art', 'sounds', name)
        shutil.rmtree(out, ignore_errors=True); os.makedirs(out)
        for ref in sorted({r for r in keys.values() if r[0] == s}):
            shutil.copy(os.path.join(src[s], 'sounds', ref[2:] + '.wav'), out)
sounds = {}
for ref in sorted(set(keys.values())):
    wav = os.path.join(ROOT, 'art', 'sounds', SETS[ref[0]], ref[2:] + '.wav')
    mp3 = subprocess.run(['ffmpeg', '-v', 'error', '-i', wav, '-ac', '1', '-ar', '22050', '-b:a', '40k', '-f', 'mp3', '-'],
                         check=True, capture_output=True).stdout
    sounds[ref] = 'data:audio/mpeg;base64,' + base64.b64encode(mp3).decode()
out = os.path.join(ROOT, 'sounds.js')
with open(out, 'w') as fh:
    fh.write('// Generated by tools/pack_sounds.py from art/sounds. Do not edit by hand.\n')
    fh.write('window.SOUNDS = ' + json.dumps(sounds) + ';\n')
    fh.write('window.SOUND_KEYS = ' + json.dumps(keys) + ';\n')
print(len(keys), 'keys,', len(sounds), 'files ->', out, os.path.getsize(out) // 1024, 'KB')
